/*
 * Ship blueprint generator: public/ships/<id>.svg → public/ships/blueprint/<id>.svg
 *
 * The Ship Customization screen shows hulls as line-art blueprints instead of
 * the coloured battle art. The blueprints are derived from the battle SVGs so
 * the two never drift apart in shape: rerun `npm run sprites:blueprints`
 * after changing or adding a ship SVG.
 *
 * Rules (the battle files are flat lists of simple shapes, parsed by regex):
 * - the engine glow group and every shape without its own stroke (colour
 *   accents, turret centre dots) are dropped;
 * - stroked shapes smaller than MIN_DETAIL_AREA (barrels, rivets) are
 *   dropped, which is what keeps the blueprint less busy than the art;
 * - kept shapes are filled with the blueprint paper (`--bp-paper`), so a
 *   shape still hides the outlines it covers, and outlined with
 *   currentColor at a fixed screen width (non-scaling stroke): heavy for the
 *   art's outer lines (stroke ≥ 2), thin for inner detail;
 * - a dashed centreline is drawn on top.
 * The root keeps id="ship" and the viewBox, so ship-icons.ts sizes apply.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const srcDir = join(root, 'public', 'ships');
const outDir = join(srcDir, 'blueprint');

const MIN_DETAIL_AREA = 30;
const HEAVY_SOURCE_STROKE = 2;
const GEOMETRY = ['x', 'y', 'width', 'height', 'rx', 'ry', 'cx', 'cy', 'r', 'points', 'x1', 'y1', 'x2', 'y2', 'd', 'transform'];

const parseAttrs = (s) => Object.fromEntries([...s.matchAll(/([\w:-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
const num = (v) => Number.parseFloat(v ?? '0');

/* Rough size of a shape (bounding-box area) used only for the detail cut. */
function area(tag, a) {
  switch (tag) {
    case 'circle': return (2 * num(a.r)) ** 2;
    case 'ellipse': return 4 * num(a.rx) * num(a.ry);
    case 'rect': return num(a.width) * num(a.height);
    case 'line': return Math.hypot(num(a.x2) - num(a.x1), num(a.y2) - num(a.y1)) * 4;
    case 'polygon': {
      const p = a.points.trim().split(/[\s,]+/).map(Number);
      const xs = p.filter((_, i) => i % 2 === 0);
      const ys = p.filter((_, i) => i % 2 === 1);
      return (Math.max(...xs) - Math.min(...xs)) * (Math.max(...ys) - Math.min(...ys));
    }
    default: return Infinity; // paths: always structural in the current art
  }
}

function convert(svg) {
  const [, rootAttrs] = svg.match(/<svg([^>]*)>/);
  const { viewBox } = parseAttrs(rootAttrs);
  const [, , w, h] = viewBox.split(/\s+/).map(Number);
  const body = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<g style="fill: var\(--ship-engine[^"]*">[\s\S]*?<\/g>/g, '');

  const out = [];
  // Group attributes (stroke, fill none) are inherited by the shapes inside.
  const groups = [];
  for (const m of body.matchAll(/<(\/?)(\w+)([^>]*?)(\/?)>/g)) {
    const [, closing, tag, attrText, selfClosing] = m;
    if (tag === 'svg') continue;
    if (tag === 'g') {
      if (closing) groups.pop();
      else groups.push(parseAttrs(attrText));
      continue;
    }
    if (closing || !selfClosing) continue;
    const a = { ...Object.assign({}, ...groups), ...parseAttrs(attrText) };
    const stroked = a.stroke && a.stroke !== 'none';
    if (!stroked || area(tag, a) < MIN_DETAIL_AREA) continue;
    const heavy = num(a['stroke-width'] || '1') >= HEAVY_SOURCE_STROKE;
    const geometry = GEOMETRY.filter((k) => a[k] !== undefined).map((k) => `${k}="${a[k]}"`).join(' ');
    const fill = a.fill === 'none' ? 'fill="none"' : 'style="fill: var(--bp-paper, #06141f)"';
    const dash = a['stroke-dasharray'] ? ` stroke-dasharray="${a['stroke-dasharray']}"` : '';
    const opacity = heavy ? '' : ' stroke-opacity="0.7"';
    out.push(`  <${tag} ${geometry} ${fill} stroke="currentColor" stroke-width="${heavy ? 1.5 : 0.9}"${opacity}${dash} stroke-linejoin="round" vector-effect="non-scaling-stroke"/>`);
  }
  out.push(`  <line x1="0" y1="${h / 2}" x2="${w}" y2="${h / 2}" stroke="currentColor" stroke-width="0.8" stroke-opacity="0.4" stroke-dasharray="10 4 2 4" vector-effect="non-scaling-stroke"/>`);
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" id="ship" viewBox="${viewBox}" preserveAspectRatio="xMidYMid meet">`,
    '  <!-- Generated by scripts/ship-blueprints/generate.mjs from ../<id>.svg; do not edit. -->',
    ...out,
    '</svg>',
    '',
  ].join('\n');
}

mkdirSync(outDir, { recursive: true });
for (const file of readdirSync(srcDir).filter((f) => f.endsWith('.svg'))) {
  writeFileSync(join(outDir, file), convert(readFileSync(join(srcDir, file), 'utf8')));
  console.log('blueprint', file);
}
